"""独夫进攻 v2: compile the prefix groups' `next.share` into the skill's offense table.

    uv run python workspaces/WhereWindsMeet/tools/dufu_moveid/s5_offense_table.py

In: data/moveid/p1/teacher_prefix/prefix.json (阶段一, 97 groups) and data/moveid/teacher_prefix/prefix.json
(阶段二, 87 groups) -- only `groups[gid].next.share`, the share of a group's contacts whose chain has a following
contact (s3b_prefix.py). Out: workspaces/WhereWindsMeet/skills/lib/dufu-offense-table.js, one array per phase in the
head's grp-label order, with the idle label (97 / 87) appended as null. skills cannot read data at run time.

The design (docs/dufu-offense-design.md 5.2) uses `next.share` only as the "the chain ends here" prior: for the 30 f
right after a contact P(empty f) is derived from it in lib/dufu-offense.js (the low-share anchor of 3.2, scaled by
share); after 30 f the group says nothing about the gap and the pooled `quiet_far` anchor is used. Nothing else is
taken from the prefix table, so a regeneration after retraining is one line.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from common import REPO, WS, read_json, write_json  # noqa: E402

P1 = REPO / "data" / "moveid" / "p1" / "teacher_prefix" / "prefix.json"
P2 = REPO / "data" / "moveid" / "teacher_prefix" / "prefix.json"
JS = REPO / "workspaces" / WS / "skills" / "lib" / "dufu-offense-table.js"
OUT = REPO / "data" / "moveid" / "offense" / "next_share.json"


def shares(path: Path) -> tuple[list[float | None], list[str]]:
    d = read_json(path)
    gs = d["groups"]
    gs = sorted(gs, key=lambda g: g["gid"])
    assert [g["gid"] for g in gs] == list(range(len(gs))), f"{path}: gids are not 0..n-1"
    return [float(g["next"]["share"]) for g in gs] + [None], [g["name"] for g in gs]


def main() -> None:
    s1, n1 = shares(P1)
    s2, n2 = shares(P2)
    assert len(s1) == 98 and len(s2) == 88, (len(s1), len(s2))
    write_json(OUT, {"1": {"groups": n1, "next_share": s1}, "2": {"groups": n2, "next_share": s2}})
    js = (
        "// GENERATED by tools/dufu_moveid/s5_offense_table.py from data/moveid/p1/teacher_prefix/prefix.json and\n"
        "// data/moveid/teacher_prefix/prefix.json (next.share only): do not edit.\n"
        "// 进攻 v2: per prefix group the share of its contacts whose chain has a following contact (s3b_prefix.py),\n"
        "// in the head's grp-label order; the last entry is the idle label (null = no group). The empty-window\n"
        "// probabilities are derived from it in lib/dufu-offense.js (docs/dufu-offense-design.md 5.2).\n"
        "/** @type {Record<1 | 2, (number | null)[]>} */\n"
        "export const NEXT_SHARE = {\n"
        f"    1: {json.dumps(s1)},\n"
        f"    2: {json.dumps(s2)},\n"
        "};\n"
    )
    JS.write_text(js, encoding="utf-8")
    print(f"{JS.relative_to(REPO)}: p1 {len(s1) - 1} groups, p2 {len(s2) - 1} groups")


if __name__ == "__main__":
    main()
